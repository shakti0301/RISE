// Arithmetic operators: *, /, **, %, +, -
let agesuresh = 2026 - 1990;
console.log(agesuresh * 2, agesuresh / 2, agesuresh ** 2); // multiply, divide, power

// Assignment operators
let x = 10 + 5;
x += 10; // x = x + 10 (addition assignment)
x++; // x = x + 1 (increment by 1)
x--; // x = x - 1 (decrement by 1)
console.log(x);
